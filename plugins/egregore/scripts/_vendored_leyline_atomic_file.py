from __future__ import annotations

import contextlib
import os
import stat
import sys
import tempfile
from pathlib import Path

#: mkstemp's own mode: only the owner may read the file.
PRIVATE = 0o600


def write_atomic(
    path: str | os.PathLike[str],
    content: str | bytes,
    *,
    mode: int | None = PRIVATE,
) -> None:
    """Write ``content`` to ``path`` through a temp file and a rename.

    The temp name is unique per call: a fixed sibling path let one
    process's ``os.replace`` publish or clobber another's half-written
    file. ``str`` is encoded as strict UTF-8; pass ``bytes`` to choose
    another encoding or error policy.

    ``mode`` defaults to owner-only. ``None`` keeps the mode the target
    already has, or for a new file the mode ``open`` would give it, so a
    save never narrows who may read the file.

    If writing or renaming fails, ``KeyboardInterrupt`` included, the
    temp file is removed, the error propagates, and ``path`` is
    unchanged. If the directory sync after the rename fails, the error
    propagates with the new content already in place. The file and then
    its directory are synced, so a crash after return loses neither the
    data nor the rename.
    """
    target = Path(path)
    data = content.encode("utf-8") if isinstance(content, str) else content
    if mode is None:
        mode = _current_mode(target)
    fd, tmp_name = tempfile.mkstemp(
        suffix=".tmp", prefix=target.name + ".", dir=str(target.parent)
    )
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, target)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp_name)
        raise
    _fsync_directory(target.parent)


def _current_mode(target: Path) -> int:
    """Return the mode ``target`` has, or the one ``open`` would give it."""
    try:
        return stat.S_IMODE(target.stat().st_mode)
    except FileNotFoundError:
        umask = os.umask(0)
        os.umask(umask)
        return 0o666 & ~umask


def _fsync_directory(directory: Path) -> None:
    """Sync ``directory`` so a rename inside it survives a crash.

    Windows cannot open a directory for fsync, and NTFS journals
    metadata changes such as a rename. The sync is skipped there.
    """
    if sys.platform == "win32":
        return
    fd = os.open(directory, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)
