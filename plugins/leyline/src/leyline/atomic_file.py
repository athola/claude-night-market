"""Replace a file in one rename, so a reader never sees half of it.

Standard library only and Python 3.9 compatible: hooks import a copy of
this module under the operator's bare ``python3``. Plugins that cannot
import leyline carry a copy generated by ``scripts/sync_vendored.py``;
edit this file, never a copy.
"""

from __future__ import annotations

import contextlib
import functools
import json
import os
import stat
import sys
import tempfile
import time
from collections.abc import Callable, Generator
from pathlib import Path
from typing import Any

try:
    import fcntl
except ImportError:  # Windows: file_lock takes msvcrt.locking instead
    fcntl = None  # type: ignore[assignment]  # None sentinel: file_lock branches on it

#: mkstemp's own mode: only the owner may read the file.
PRIVATE = 0o600

#: How often a timed ``file_lock`` retries a lock another process holds.
_LOCK_POLL_SECONDS = 0.05


@contextlib.contextmanager
def file_lock(
    path: str | os.PathLike[str], *, timeout: float | None = None
) -> Generator[None, None, None]:
    """Hold the exclusive lock every writer of ``path`` agrees on.

    The lock file is ``<name>.lock`` beside ``path``. ``write_atomic`` keeps
    a file whole but cannot stop a load-modify-write from dropping another
    writer's change; holding this across the whole cycle does.

    ``timeout=None`` waits as long as the holder keeps the lock. A number
    polls without blocking until that many seconds have passed, then raises
    ``TimeoutError`` naming the lock file, for a hook that would rather
    give up than be killed mid-wait. ``TimeoutError`` is an ``OSError``, so
    a caller that treats the two differently catches it first.

    On Windows the lock is ``msvcrt.locking`` on byte 0, released
    explicitly because Windows may free a lock on a closed handle late.
    There an untimed wait is ``LK_LOCK``, which raises ``OSError`` after
    about ten seconds of contention. A platform with neither ``fcntl`` nor
    ``msvcrt`` takes no lock.
    """
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    lock_path = target.with_name(target.name + ".lock")
    with open(lock_path, "a") as lock:
        if sys.platform == "win32":
            # Byte 0 of the file: an append open sits at end of file.
            import msvcrt  # noqa: PLC0415 - Windows only: imported once the platform is known, so a faked platform in a test can supply it

            lock.seek(0)
            if timeout is None:
                msvcrt.locking(lock.fileno(), msvcrt.LK_LOCK, 1)
            else:
                _poll(
                    functools.partial(
                        msvcrt.locking, lock.fileno(), msvcrt.LK_NBLCK, 1
                    ),
                    OSError,
                    lock_path,
                    timeout,
                )
            try:
                yield
            finally:
                lock.seek(0)
                msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)
            return
        if fcntl is not None:
            if timeout is None:
                fcntl.flock(lock, fcntl.LOCK_EX)
            else:
                _poll(
                    functools.partial(fcntl.flock, lock, fcntl.LOCK_EX | fcntl.LOCK_NB),
                    BlockingIOError,
                    lock_path,
                    timeout,
                )
        try:
            yield
        finally:
            if fcntl is not None:
                fcntl.flock(lock, fcntl.LOCK_UN)


def _poll(
    attempt: Callable[[], None],
    busy: type[OSError],
    lock_path: Path,
    timeout: float,
) -> None:
    """Retry ``attempt`` while it raises ``busy``, up to ``timeout`` seconds."""
    deadline = time.monotonic() + timeout
    while True:
        try:
            attempt()
            return
        except busy:
            if time.monotonic() >= deadline:
                raise TimeoutError(
                    f"lock {lock_path} held for over {timeout}s"
                ) from None
            time.sleep(_LOCK_POLL_SECONDS)


def read_json_object(
    path: str | os.PathLike[str], default: dict[str, Any]
) -> dict[str, Any]:
    """Return the JSON object at ``path``, or ``default``.

    A state file that is missing, unreadable, not JSON, or valid JSON of
    another shape (``[]`` after a bad write) all mean "no state". Readers
    that caught only the decode error raised on ``[].get`` instead.
    """
    try:
        with open(path, encoding="utf-8") as handle:
            loaded = json.load(handle)
    except (OSError, ValueError):
        return default
    return loaded if isinstance(loaded, dict) else default


def write_atomic(
    path: str | os.PathLike[str],
    content: str | bytes,
    *,
    mode: int | None = PRIVATE,
) -> None:
    """Write ``content`` to ``path`` through a temp file and a rename.

    The temp name is unique per call: a fixed sibling path let one
    process's ``os.replace`` publish or clobber another's half-written
    file. ``str`` is encoded as strict UTF-8. Pass ``bytes`` to choose
    another encoding or error policy.

    ``mode`` defaults to owner-only. ``None`` keeps the mode the target
    already has, or for a new file the mode ``open`` would give it, so a
    save never narrows who may read the file.

    If writing or renaming fails, ``KeyboardInterrupt`` included, the
    temp file is removed, the error propagates, and ``path`` is
    unchanged. If the directory sync after the rename fails, the error
    propagates with the new content already in place. The file and then
    its directory are synced, so a crash after return loses neither the
    data nor the rename.
    """
    target = Path(path)
    data = content.encode("utf-8") if isinstance(content, str) else content
    if mode is None:
        mode = _current_mode(target)
    fd, tmp_name = tempfile.mkstemp(
        suffix=".tmp", prefix=target.name + ".", dir=str(target.parent)
    )
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, target)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp_name)
        raise
    _fsync_directory(target.parent)


def _current_mode(target: Path) -> int:
    """Return the mode ``target`` has, or the one ``open`` would give it."""
    try:
        return stat.S_IMODE(target.stat().st_mode)
    except FileNotFoundError:
        umask = os.umask(0)
        os.umask(umask)
        return 0o666 & ~umask


def _fsync_directory(directory: Path) -> None:
    """Sync ``directory`` so a rename inside it survives a crash.

    Windows cannot open a directory for fsync, and NTFS journals
    metadata changes such as a rename. The sync is skipped there.
    """
    if sys.platform == "win32":
        return
    fd = os.open(directory, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)
